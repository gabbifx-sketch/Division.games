const gameIcon = document.getElementById("game-icon-image");
const gamesContainer = document.querySelector(".display-games");

const searchInput = document.querySelector("#game-search");
const searchResults = document.querySelector("#search-results");
const searchClose = document.querySelector("#search-close");

const gameLaunchOverlay =
    document.querySelector("#gameLaunchOverlay");

const launchGameName =
    document.querySelector("#launchGameName");

const launchStatus =
    document.querySelector("#launchStatus");


// =========================================
// CREATE GAME CARD
// =========================================

function createGameCard(game) {

    const card = document.createElement("a");

    card.href = "#";
    card.className = "hero-game-card";
    card.title = game.title;

    card.innerHTML = `
        <img
            src="${game.img}"
            alt="${game.title}"
            loading="lazy"
        >

        <p>${game.title}</p>
    `;


    // =========================================
    // CLICK GAME
    // =========================================

    card.addEventListener("click", function(event) {

        event.preventDefault();

        launchGame(game);

    });


    return card;
}


// =========================================
// LAUNCH GAME
// =========================================

function launchGame(game) {

    // If launch overlay doesn't exist
    if (!gameLaunchOverlay) {

        window.location.href =
            "./play.html?game=" +
            encodeURIComponent(game.id);

        return;
    }


    // GAME ICON

    if (gameIcon) {

        gameIcon.innerHTML = `
            <img
                class="game-icon-img-work"
                src="${game.img}"
                alt="${game.title}"
            >
        `;

    }


    // GAME NAME

    if (launchGameName) {

        launchGameName.innerText =
            "Launching " + game.title;

    }


    // FIRST MESSAGE

    if (launchStatus) {

        launchStatus.innerText =
            "Getting everything ready...";

    }


    // SHOW OVERLAY

    gameLaunchOverlay.classList.add("active");


    // UPDATE MESSAGE

    setTimeout(function() {

        if (launchStatus) {

            launchStatus.innerText =
                "Starting game...";

        }

    }, 400);


    setTimeout(function() {

        if (launchStatus) {

            launchStatus.innerText =
                "Loading game...";

        }

    }, 700);


    // GO TO PLAY PAGE

    setTimeout(function() {

        window.location.href =
            "./play.html?game=" +
            encodeURIComponent(game.id);

    }, 1000);

}


// =========================================
// DISPLAY ALL GAMES
// =========================================

function displayAllGames() {

    if (!gamesContainer) {

        console.error(
            "Division: .display-games was not found."
        );

        return;
    }


    gamesContainer.innerHTML = "";


    displayHomeGames.forEach(function(game) {

        gamesContainer.appendChild(
            createGameCard(game)
        );

    });

}


// =========================================
// SEARCH GAMES
// =========================================

function searchGames() {

    if (!searchInput || !searchResults) {
        return;
    }

    const searchText =
        searchInput.value.trim().toLowerCase();

    searchResults.innerHTML = "";

    // Nothing typed
    if (searchText === "") {
        return;
    }

    // Find games by title, ID, OR category
    const results = displayHomeGames.filter(function (game) {

        const title =
            game.title.toLowerCase();

        const id =
            game.id.toLowerCase();

        const categories =
            game.categories || [];

        // Title match
        const titleMatch =
            title.includes(searchText);

        // ID match
        const idMatch =
            id.includes(searchText);

        // Category match
        const categoryMatch =
            categories.some(function (category) {

                return category
                    .toLowerCase()
                    .includes(searchText);

            });

        return (
            titleMatch ||
            idMatch ||
            categoryMatch
        );

    });


    // =========================================
    // NO RESULTS
    // =========================================

    if (results.length === 0) {

        searchResults.innerHTML = `
            <div class="no-results">

                <h3>No games found</h3>

                <p>
                    Try searching for another game
                    or category.
                </p>

            </div>
        `;

        return;
    }


    // =========================================
    // DISPLAY RESULTS
    // =========================================

    results.forEach(function (game) {

        const result =
            document.createElement("a");

        result.className =
            "search-result";

        result.href = "#";


        result.innerHTML = `

            <img
                src="${game.img}"
                alt="${game.title}"
            >

            <div class="search-result-info">

                <span class="search-result-title">
                    ${game.title}
                </span>

                <small class="search-result-category">
                    ${(game.categories || []).join(" • ")}
                </small>

            </div>

        `;


        // =========================================
        // CLICK SEARCH RESULT
        // =========================================

        result.addEventListener(
            "click",
            function (event) {

                event.preventDefault();

                launchGame(game);

            }
        );


        searchResults.appendChild(result);

    });

}

